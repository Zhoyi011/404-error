export function getEndingStoryBeats(id: EndingId, isMobile: boolean): EndingStoryBeat[] {
  if (isMobile && MOBILE_ENDING_STORIES[id]) {
    return MOBILE_ENDING_STORIES[id]!;
  }
  return ENDING_STORIES[id];
}

export function getEndingDefinition(id: EndingId, isMobile: boolean): EndingDefinition {
  const base = ENDINGS[id];
  if (!isMobile) return base;
  const override = MOBILE_ENDING_OVERRIDES[id];
  if (!override) return base;
  return {
    ...base,
    ...override,
  };
}

